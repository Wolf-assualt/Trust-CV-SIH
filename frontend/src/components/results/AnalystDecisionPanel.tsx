import React, { useState } from 'react';
import { UserCheck, Loader2 } from 'lucide-react';
import { useInvestigation } from '../../state/investigationStore';
import type { AnalystDecision } from '../../services/api';
import { Badge } from '../ui/Badge';
import { Button } from '../ui/Button';

/**
 * Analyst Disposition panel.
 *
 * The SYSTEM ASSESSMENT (VerdictCard / TrustScoreCard) is produced by the
 * assurance pipeline. This panel is a SEPARATE, explicit human action that is
 * persisted and signed by the backend ledger. A decision is only ever displayed
 * as recorded after the backend confirms the ledger event.
 */
export const AnalystDecisionPanel: React.FC = () => {
  const {
    submitAnalystDecision,
    analystDecisions,
    scanSession,
    refreshAnalystDecisions,
  } = useInvestigation();

  const [actor, setActor] = useState('operator_ground_station');
  const [reason, setReason] = useState('');
  const [busy, setBusy] = useState<AnalystDecision | null>(null);
  const [lastError, setLastError] = useState<string | null>(null);

  const entityId = scanSession?.batch_id || scanSession?.scan_id || null;

  const handleDecide = async (decision: AnalystDecision) => {
    setBusy(decision);
    setLastError(null);
    try {
      const event = await submitAnalystDecision(decision, actor.trim() || 'operator_ground_station', {
        entityId: entityId ?? undefined,
        scanId: scanSession?.scan_id,
        reason: reason.trim() || undefined,
      });
      if (!event) {
        // The backend did not confirm — nothing is shown as recorded.
        setLastError('The backend did not confirm the decision. It has NOT been recorded.');
      } else {
        setReason('');
      }
    } finally {
      setBusy(null);
    }
  };

  const latest = analystDecisions.length ? analystDecisions[analystDecisions.length - 1] : null;

  return (
    <section
      style={{
        backgroundColor: 'var(--surface)',
        border: '1px solid var(--border)',
        borderRadius: '0.625rem',
        padding: '1.5rem',
        boxShadow: 'var(--card-shadow)',
        display: 'flex',
        flexDirection: 'column',
        gap: '1rem',
      }}
    >
      <div
        style={{
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          flexWrap: 'wrap',
          gap: '0.75rem',
          borderBottom: '1px solid var(--border-subtle)',
          paddingBottom: '0.75rem',
        }}
      >
        <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
          <UserCheck size={16} strokeWidth={1.5} style={{ color: 'var(--text-muted)' }} />
          <h3
            style={{ fontSize: '16px', fontWeight: 600, color: 'var(--text-primary)', letterSpacing: '-0.01em', margin: 0 }}
          >
            Analyst Disposition (Human Decision)
          </h3>
        </div>

        {latest ? (
          <Badge variant="success" size="sm">
            {analystDecisions.length} RECORDED // LATEST SEQ {latest.sequence}
          </Badge>
        ) : (
          <Badge variant="warning" size="sm">NO DECISION RECORDED</Badge>
        )}
      </div>

      <p style={{ fontSize: '0.8125rem', color: 'var(--text-secondary)', margin: 0, lineHeight: 1.5 }}>
        The assessment above is generated by the assurance pipeline. An analyst disposition is a separate
        explicit action, cryptographically signed and persisted by the backend ledger.
      </p>

      {!entityId ? (
        <div
          style={{
            padding: '0.875rem 1rem',
            backgroundColor: 'var(--surface-elevated)',
            border: '1px dashed var(--border)',
            borderRadius: '0.375rem',
            fontSize: '0.8125rem',
            color: 'var(--text-muted)',
          }}
        >
          UNAVAILABLE — no backend scan entity is loaded. Run a real scan before recording a disposition.
        </div>
      ) : (
        <>
          <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(220px, 1fr))', gap: '0.75rem' }}>
            <div>
              <label htmlFor="analyst-actor" style={{ display: 'block', fontSize: '11px', color: 'var(--text-muted)', marginBottom: '4px', letterSpacing: '0.02em' }}>
                Analyst identity
              </label>
              <input
                id="analyst-actor"
                type="text"
                value={actor}
                onChange={e => setActor(e.target.value)}
                style={{
                  width: '100%', padding: '0.5rem', backgroundColor: 'var(--surface-elevated)',
                  border: '1px solid var(--border)', borderRadius: '0.375rem',
                  color: 'var(--text-primary)', fontSize: '0.8125rem',
                }}
                className="font-mono"
              />
            </div>
            <div>
              <label htmlFor="analyst-reason" style={{ display: 'block', fontSize: '11px', color: 'var(--text-muted)', marginBottom: '4px', letterSpacing: '0.02em' }}>
                Justification (optional)
              </label>
              <input
                id="analyst-reason"
                type="text"
                value={reason}
                onChange={e => setReason(e.target.value)}
                placeholder="e.g. cross-checked against source imagery"
                style={{
                  width: '100%', padding: '0.5rem', backgroundColor: 'var(--surface-elevated)',
                  border: '1px solid var(--border)', borderRadius: '0.375rem',
                  color: 'var(--text-primary)', fontSize: '0.8125rem',
                }}
                className="font-mono"
              />
            </div>
          </div>

          <div style={{ display: 'flex', gap: '0.5rem', flexWrap: 'wrap' }}>
            <Button variant="outline" size="sm" style={{ flex: 1 }} disabled={busy !== null}
              onClick={() => handleDecide('ACCEPT')} icon={busy === 'ACCEPT' ? <Loader2 size={13} /> : undefined}>
              ACCEPT
            </Button>
            <Button variant="outline" size="sm" style={{ flex: 1 }} disabled={busy !== null}
              onClick={() => handleDecide('REVIEW')} icon={busy === 'REVIEW' ? <Loader2 size={13} /> : undefined}>
              REVIEW
            </Button>
            <Button variant="danger" size="sm" style={{ flex: 1 }} disabled={busy !== null}
              onClick={() => handleDecide('QUARANTINE')} icon={busy === 'QUARANTINE' ? <Loader2 size={13} /> : undefined}>
              QUARANTINE
            </Button>
          </div>

          {lastError && (
            <div
              role="alert"
              style={{
                padding: '0.75rem 1rem', backgroundColor: 'var(--critical-surface)',
                border: '1px solid var(--critical-border)', borderRadius: '0.375rem',
                fontSize: '0.75rem', color: 'var(--critical-text)',
              }}
            >
              {lastError}
            </div>
          )}
        </>
      )}

      {latest ? (
        <div
          style={{
            padding: '0.75rem 1rem', backgroundColor: 'var(--surface-elevated)',
            border: '1px solid var(--border-subtle)', borderRadius: '0.375rem',
            fontSize: '0.6875rem', color: 'var(--text-secondary)',
            display: 'flex', flexDirection: 'column', gap: '0.25rem', wordBreak: 'break-all',
          }}
          className="font-mono"
        >
          <span style={{ color: 'var(--text-muted)' }}>Latest recorded ledger event (backend-confirmed)</span>
          <span>decision payload seq: {latest.sequence}</span>
          <span>actor: {latest.actor}</span>
          <span>entity_id: {latest.entity_id}</span>
          <span>scan_id: {latest.scan_id ?? 'N/A'}</span>
          <span>event hash: {latest.current_hash}</span>
          <span>signature: {latest.signature ? 'PRESENT (Ed25519)' : 'ABSENT'}</span>
          <span>timestamp: {latest.timestamp ?? 'N/A'}</span>
        </div>
      ) : (
        <div style={{ fontSize: '0.75rem', color: 'var(--text-muted)' }}>
          No analyst decisions are persisted for this entity. This client never fabricates a decision record.
        </div>
      )}

      {entityId && (
        <Button variant="ghost" size="sm" onClick={() => refreshAnalystDecisions(entityId)}>
          RELOAD RECORDED DECISIONS FROM BACKEND
        </Button>
      )}
    </section>
  );
};
